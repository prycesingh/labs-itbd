"use client";

import { useState } from "react";
import { toast } from "sonner";

import type { M365Action } from "@/lib/labs/simulators/m365/reducer";
import type { M365OfficeDeployConfig, M365State } from "@/lib/labs/simulators/m365/types";
import { FormGroup, Pill } from "./m365-ui";
