const UPDATE_CHANNELS: { id: M365OfficeDeployConfig["updateChannel"]; desc: string }[] = [
  { id: "Current", desc: "Latest features as they release (~monthly). Pilot / IT." },
  { id: "Monthly Enterprise", desc: "Latest features on the 2nd Tuesday each month. Mainstream production. Recommended." },
  { id: "Semi-Annual Enterprise", desc: "Most stable — released January and July. Validation-heavy orgs." },
  { id: "Semi-Annual Enterprise (Preview)", desc: "Preview of the next Semi-Annual Enterprise release — March and September." },
  { id: "Current Preview", desc: "Preview of the next Current Channel release." },
  { id: "Beta", desc: "Weekly Insider builds. Pre-release testing only." },
];

