// ===================== Investigation graph tab =====================
// Real computed radial SVG layout, ported faithfully from source's
// graphTab(): entities placed at angle = 2*PI*i/n around a central incident
// node at a fixed radius, connected to the center by dashed lines, color-coded
// by entity type. Colors are ported 1:1 from source's `nodeColors` map.

const GRAPH_WIDTH = 1000;
const GRAPH_HEIGHT = 420;
const GRAPH_RADIUS = 150;

const NODE_COLORS: Record<string, string> = {
  User: "#5b9bd5",
  Host: "#f9a825",
  IP: "#cf2030",
  URL: "#9c27b0",
  File: "#107c10",
  Process: "#d97900",
  "Azure resource": "#607d8b",
};
const DEFAULT_NODE_COLOR = "#607d8b";
const INCIDENT_NODE_COLOR = "#cf2030";

function GraphTab({ incident }: { incident: SentinelIncident }) {
  const cx = GRAPH_WIDTH / 2;
  const cy = GRAPH_HEIGHT / 2;
  const entities = incident.entities;

  const nodes = useMemo(
    () =>
      entities.map((e, i) => {
        const angle = (2 * Math.PI * i) / entities.length;
        return { x: cx + Math.cos(angle) * GRAPH_RADIUS, y: cy + Math.sin(angle) * GRAPH_RADIUS, entity: e };
      }),
    [entities, cx, cy],
  );

  return (
    <div>
      <div className={styles.graph}>
        <svg width="100%" height="100%" viewBox={`0 0 ${GRAPH_WIDTH} ${GRAPH_HEIGHT}`} preserveAspectRatio="xMidYMid meet">
          {nodes.map((n, i) => (
            <line key={`line-${i}`} x1={cx} y1={cy} x2={n.x} y2={n.y} stroke="#3a6ea5" strokeWidth={1.5} strokeDasharray="4 3" opacity={0.6} />
          ))}
          <g transform={`translate(${cx},${cy})`}>
            <circle r={34} fill={INCIDENT_NODE_COLOR} stroke="#fff" strokeWidth={3} />
            <text y={4} textAnchor="middle" fill="#fff" fontSize={12} fontWeight={600}>
              INCIDENT
            </text>
            <text y={60} textAnchor="middle" fill="#fff" fontSize={11}>
              {incident.id}
            </text>
          </g>
          {nodes.map((n, i) => {
            const color = NODE_COLORS[n.entity.type] ?? DEFAULT_NODE_COLOR;
            return (
              <g key={`node-${i}`} transform={`translate(${n.x},${n.y})`}>
                <circle r={22} fill={color} stroke="#fff" strokeWidth={2} />
                <text y={5} textAnchor="middle" fill="#fff" fontSize={11} fontWeight={600}>
                  {n.entity.type.substring(0, 1)}
                </text>
                <text y={40} textAnchor="middle" fill="#fff" fontSize={11}>
                  {n.entity.name}
                </text>
              </g>
            );
          })}
        </svg>
      </div>
      <div className={styles.legend}>
        {Object.entries(NODE_COLORS).map(([type, color]) => (
          <span key={type} className={styles.legendItem}>
            <span className={styles.legendDot} style={{ background: color }} />
            {type}
          </span>
        ))}
      </div>
      <div style={{ fontSize: 12, color: "#605e5c", marginTop: 8 }}>
        Investigation graph - showing entity relationships extracted from the incident&apos;s alerts. Click nodes in the real portal to drill into entity timelines.
      </div>
    </div>
  );
}

