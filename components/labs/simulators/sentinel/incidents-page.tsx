// ===================== Comments tab =====================

function CommentsTab({ incident, dispatch }: { incident: SentinelIncident; dispatch: React.Dispatch<SentinelAction> }) {
  const [draft, setDraft] = useState("");

  function post() {
    const text = draft.trim();
    if (!text) return;
    dispatch({ type: "ADD_INCIDENT_COMMENT", id: incident.id, author: CURRENT_USER, text });
    toast.success("Comment added");
    setDraft("");
  }

  return (
    <div>
      {incident.comments.map((c) => (
        <div key={c.id} className={styles.card} style={{ marginBottom: 6 }}>
          <div style={{ fontSize: 11, color: "#605e5c" }}>
            {c.author} &middot; {new Date(c.time).toLocaleString()}
          </div>
          <div style={{ fontSize: 13, marginTop: 4 }}>{c.text}</div>
        </div>
      ))}
      <div className={styles.card}>
        <div className={styles.cardTitle}>Add comment</div>
        <textarea
          className={styles.textarea}
          rows={3}
          placeholder="Investigation notes, links to playbooks, etc."
          value={draft}
          onChange={(e) => setDraft(e.target.value)}
        />
        <div style={{ marginTop: 8 }}>
          <button type="button" className={styles.btn} onClick={post}>
            Post comment
          </button>
        </div>
      </div>
    </div>
  );
}

// ===================== Detail flyout =====================

function IncidentDetailFlyout({ incident, dispatch, onClose }: { incident: SentinelIncident; dispatch: React.Dispatch<SentinelAction>; onClose: () => void }) {
  const [tab, setTab] = useState<DetailTabKey>("overview");
  const [ownerDraft, setOwnerDraft] = useState(incident.owner);

  function setStatus(status: SentinelIncidentStatus) {
    dispatch({ type: "UPDATE_INCIDENT", id: incident.id, patch: { status } });
    toast.success(`Incident ${incident.id} set to ${status}`);
    if (status === "Closed") onClose();
  }

  function assignToMe() {
    dispatch({ type: "UPDATE_INCIDENT", id: incident.id, patch: { owner: CURRENT_USER } });
    setOwnerDraft(CURRENT_USER);
    toast.success("Incident assigned to you");
  }

  function saveOwner() {
    const owner = ownerDraft.trim();
    if (!owner || owner === incident.owner) return;
    dispatch({ type: "UPDATE_INCIDENT", id: incident.id, patch: { owner } });
    toast.success(`Owner updated to ${owner}`);
  }

  const tabsWithCounts = DETAIL_TABS.map((t) => ({
    key: t.key,
    label: t.key === "alerts" ? `${t.label} (${incident.alertsCount})` : t.key === "entities" ? `${t.label} (${incident.entitiesCount})` : t.label,
  }));

  return (
    <Flyout
      title={incident.title}
      subtitle={incident.id}
      onClose={onClose}
      tabs={<SubTabBar tabs={tabsWithCounts} active={tab} onChange={(k) => setTab(k as DetailTabKey)} />}
      footer={
        <>
          <div style={{ flex: 1, display: "flex", alignItems: "center", gap: 8 }}>
            <input
              className={styles.input}
              style={{ width: 220 }}
              value={ownerDraft}
              onChange={(e) => setOwnerDraft(e.target.value)}
              placeholder="Owner email"
            />
            <button type="button" className={styles.btnOutline} onClick={saveOwner}>
              Save owner
            </button>
          </div>
          <NativeSelect
            value={incident.status}
            onChange={(v) => setStatus(v as SentinelIncidentStatus)}
            options={[
              { value: "New", label: "New" },
              { value: "Active", label: "Active" },
              { value: "Closed", label: "Closed" },
            ]}
          />
          <button type="button" className={styles.btnOutline} onClick={assignToMe}>
            Assign to me
          </button>
          <button type="button" className={styles.btn} onClick={() => setStatus("Closed")}>
            Close incident
          </button>
        </>
      }
    >
      <div style={{ display: "flex", flexWrap: "wrap", gap: 18, fontSize: 12, marginBottom: 14, paddingBottom: 14, borderBottom: "1px solid #e1dfdd" }}>
        <div>
          <div style={{ color: "#605e5c" }}>Severity</div>
          <SeverityBadge severity={incident.severity} />
        </div>
        <div>
          <div style={{ color: "#605e5c" }}>Status</div>
          <StatusPill tone={statusTone(incident.status)}>{incident.status}</StatusPill>
        </div>
        <div>
          <div style={{ color: "#605e5c" }}>Owner</div>
          <strong>{incident.owner}</strong>
        </div>
        <div>
          <div style={{ color: "#605e5c" }}>Alerts</div>
          <strong>{incident.alertsCount}</strong>
        </div>
        <div>
          <div style={{ color: "#605e5c" }}>Entities</div>
          <strong>{incident.entitiesCount}</strong>
        </div>
        <div>
          <div style={{ color: "#605e5c" }}>Created</div>
          <strong>{ago(incident.created)}</strong>
        </div>
        <div>
          <div style={{ color: "#605e5c" }}>Last modified</div>
          <strong>{ago(incident.lastModified)}</strong>
        </div>
      </div>

      {tab === "overview" && <OverviewTab incident={incident} />}
      {tab === "alerts" && <AlertsTab incident={incident} />}
      {tab === "entities" && <EntitiesTab incident={incident} />}
      {tab === "graph" && <GraphTab incident={incident} />}
      {tab === "evidence" && <EvidenceTab />}
      {tab === "comments" && <CommentsTab incident={incident} dispatch={dispatch} />}
    </Flyout>
  );
}

// ===================== List page =====================

type SeverityFilter = (typeof SEVERITY_FILTERS)[number];
type StatusFilter = (typeof STATUS_FILTERS)[number];

export function IncidentsPage({ state, dispatch }: { state: SentinelState; dispatch: React.Dispatch<SentinelAction> }) {
  const [severityFilter, setSeverityFilter] = useState<SeverityFilter>("all");
  const [statusFilter, setStatusFilter] = useState<StatusFilter>("all");
  const [selectedId, setSelectedId] = useState<string | null>(null);

  const filtered = useMemo(
    () =>
      state.incidents.filter((i) => {
        if (severityFilter !== "all" && i.severity !== severityFilter) return false;
        if (statusFilter !== "all" && i.status !== statusFilter) return false;
        return true;
      }),
    [state.incidents, severityFilter, statusFilter],
  );

  const selected = selectedId ? (state.incidents.find((i) => i.id === selectedId) ?? null) : null;

  const columns: DataTableColumn<SentinelIncident>[] = [
    { key: "severity", header: "Severity", render: (i) => <SeverityBadge severity={i.severity} /> },
    {
      key: "incident",
      header: "Incident",
      render: (i) => (
        <div>
          <div className={styles.rowLink}>{i.title}</div>
          <div style={{ fontSize: 11, color: "#605e5c" }}>{i.id}</div>
        </div>
      ),
    },
    { key: "alerts", header: "Alerts", render: (i) => i.alertsCount },
    { key: "entities", header: "Entities", render: (i) => i.entitiesCount },
    {
      key: "tactics",
      header: "Tactics",
      render: (i) => (
        <>
          {i.tactics.slice(0, 3).map((t) => (
            <span key={t} className={styles.mitre}>
              {t}
            </span>
          ))}
        </>
      ),
    },
    { key: "owner", header: "Owner", render: (i) => i.owner },
    { key: "status", header: "Status", render: (i) => <StatusPill tone={statusTone(i.status)}>{i.status}</StatusPill> },
    { key: "created", header: "Created", render: (i) => ago(i.created) },
    { key: "lastModified", header: "Last modified", render: (i) => ago(i.lastModified) },
  ];

  return (
    <div>
      <div className={styles.filterRow}>
        {SEVERITY_FILTERS.map((v) => (
          <button
            key={`sev-${v}`}
            type="button"
            className={`${styles.chip} ${severityFilter === v ? styles.chipActive : ""}`}
            onClick={() => setSeverityFilter(v)}
          >
            {v === "all" ? "Severity: any" : v}
          </button>
        ))}
        {STATUS_FILTERS.map((v) => (
          <button
            key={`status-${v}`}
            type="button"
            className={`${styles.chip} ${statusFilter === v ? styles.chipActive : ""}`}
            onClick={() => setStatusFilter(v)}
          >
            {v === "all" ? "Status: any" : v}
          </button>
        ))}
      </div>

      {filtered.length === 0 ? (
        <EmptyState message="No incidents match the current filter." />
      ) : (
        <DataTable columns={columns} rows={filtered} getRowKey={(i) => i.id} onRowClick={(i) => setSelectedId(i.id)} />
      )}

      {selected ? <IncidentDetailFlyout incident={selected} dispatch={dispatch} onClose={() => setSelectedId(null)} /> : null}
    </div>
  );
}
