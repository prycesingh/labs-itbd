// ===================== Alerts tab =====================
// No separate alerts array exists in this data model — synthesized purely
// from alertsCount, referencing the incident's own severity/rule/product,
// exactly matching source's alertsTab() loop (`inc.rule + ' #' + (i+1)`,
// `inc.productNames[0]`, `inc.tactics[0]`, `ago(inc.created)` repeated per row).

type SyntheticAlertRow = { index: number };

function AlertsTab({ incident }: { incident: SentinelIncident }) {
  const rows: SyntheticAlertRow[] = useMemo(() => Array.from({ length: incident.alertsCount }, (_, i) => ({ index: i })), [incident.alertsCount]);

  const columns: DataTableColumn<SyntheticAlertRow>[] = [
    { key: "severity", header: "Severity", render: () => <SeverityBadge severity={incident.severity} /> },
    { key: "alert", header: "Alert", render: (r) => `${incident.rule} #${r.index + 1}` },
    { key: "product", header: "Product", render: () => incident.productNames[0] ?? "" },
    { key: "tactic", header: "Tactic", render: () => incident.tactics[0] ?? "-" },
    { key: "time", header: "Time", render: () => ago(incident.created) },
  ];

  return <DataTable columns={columns} rows={rows} getRowKey={(r) => String(r.index)} emptyMessage="No alerts on this incident." />;
}

